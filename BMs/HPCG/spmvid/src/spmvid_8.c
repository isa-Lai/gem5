	LOOP3_LoopDesc.type   = LOOP    ;
	LOOP3_LoopDesc.valid  = VALID   ;
	LOOP3_LoopDesc.active =  ACTIVE ;
	LOOP3_LoopDesc.descInfo.loopDesc=LOOP3_metaData;
