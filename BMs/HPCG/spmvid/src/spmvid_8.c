	write_csr(0x800, *loop1Desc);     // csrrw a0 , meta_0l , meta_isa_obj1.desc_word[0];
	write_csr(0x801, *(loop1Desc+1)); // csrrw a0 , meta_0h , meta_isa_obj1.desc_word[1];

