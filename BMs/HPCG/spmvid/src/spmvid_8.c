int ComputeSPMV_ref(  int        localNumberOfRows , double **  matrixValues  ,
		int    **  mtxIndL           , int     *  nonzerosInRow ,
		double *   xv , double *   yv )
{
	for (int i=0; i< localNumberOfRows; i++)
	{
		yv[i]      = 0.0;
		double  * const cur_vals = matrixValues[i] ; // A.matrixValues is 2D array    ( A.localNumberOfRows * max(nnz))
		int     * const cur_inds = mtxIndL[i]      ; // A.mtxIndL is 2D array         ( A.localNumberOfRows * max(nnz))
		int             cur_nnz  = nonzerosInRow[i]; // nonzerosInRow is 1D array of size = A.localNumberOfRows
		//asm volatile ("Indirect_:\n");
		for (int j=0; j< cur_nnz; j++)
			yv[i] += cur_vals[j]*xv[cur_inds[j]]; // xv is being accessed in indirect way.
	}
		return 0;
}


